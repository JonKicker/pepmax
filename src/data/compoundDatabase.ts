export type CompoundStatus = 'FDA-Approved' | 'Research Peptide' | 'Compounded' | 'FDA-Approved (Rx/Compounded)';

export type RouteOfAdmin = 'SubQ' | 'IM' | 'Oral' | 'Nasal' | 'IV' | 'Topical' | 'Sublingual' | 'SubQ Implant';

export type DoseUnit = 'mg' | 'mcg' | 'IU' | 'mg/kg';

export type CompoundCategory =
  | 'Bone / Osteoporosis'
  | 'Cosmetic / Skin'
  | 'Fat Loss (Non-GLP-1)'
  | 'Fertility / Hormone'
  | 'GLP-1 / Weight Management'
  | 'Growth Hormone / GH Secretagogues'
  | 'Healing / Recovery'
